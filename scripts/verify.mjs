import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { simulate } from '../src/headless.mjs';
const dir = 'docs/proof/phase-1'; mkdirSync(dir, { recursive: true });
const test = spawnSync(process.execPath, ['--test', '--test-reporter=spec', 'tests/contract.test.mjs', 'tests/playthrough.test.mjs'], { encoding: 'utf8' });
writeFileSync(`${dir}/tests.txt`, test.stdout + test.stderr); process.stdout.write(test.stdout); process.stderr.write(test.stderr);
if (test.status !== 0) process.exit(test.status ?? 1);
const scenario = { random_motes: false, random_shades: false, player: { carried: 10 }, lanterns: Array.from({ length: 5 }, (_, i) => ({ id: `L${i + 1}`, pos: [0, 0, 0], lit: i > 0 })) };
const inputs = { frames: [{ tick: 0, interact: true }] };
writeFileSync(`${dir}/win.scenario.json`, JSON.stringify(scenario, null, 2) + '\n');
writeFileSync(`${dir}/win.inputs.json`, JSON.stringify(inputs, null, 2) + '\n');
const options = { seed: 42, ticks: 100, scenario, inputs };
writeFileSync(`${dir}/win.jsonl`, simulate(options));
const a = simulate({ seed: 42, ticks: 1200 }), b = simulate({ seed: 42, ticks: 1200 });
if (a !== b) throw new Error('Determinism failed');
writeFileSync(`${dir}/deterministic.jsonl`, a);
writeFileSync(`${dir}/verification.json`, JSON.stringify({ node: process.version, platform: process.platform, arch: process.arch, tests_exit_code: test.status, determinism: { seed: 42, ticks: 1200, byte_identical: a === b } }, null, 2) + '\n');
console.log(`Evidence written to ${dir}`);
